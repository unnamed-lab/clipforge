"""ASS subtitle generation with per-word highlighting.

One dialogue event per word keeps the active-word highlight exact without karaoke
timing drift. libass replaces events at the same alignment, which is what we want.
"""

from __future__ import annotations

from dataclasses import dataclass

from clipforge.rendering.spec import CaptionSettings, RenderSpec

ALIGNMENT = {"bottom": 2, "center": 5, "top": 8}
CHUNK_GAP_MS = 700
CHUNK_TAIL_MS = 160


@dataclass
class CaptionWord:
    start_ms: int
    end_ms: int
    text: str


def _ass_color(hex_colour: str) -> str:
    value = hex_colour.lstrip("#")
    red, green, blue = value[0:2], value[2:4], value[4:6]
    return f"&H00{blue}{green}{red}".upper()


def _ass_time(ms: int) -> str:
    ms = max(0, int(ms))
    hours, remainder = divmod(ms, 3_600_000)
    minutes, remainder = divmod(remainder, 60_000)
    seconds, millis = divmod(remainder, 1000)
    centis = millis // 10
    return f"{hours}:{minutes:02d}:{seconds:02d}.{centis:02d}"


def _escape(text: str) -> str:
    cleaned = text.replace("\\", "\\\\").replace("{", "(").replace("}", ")")
    return cleaned.replace("\n", " ").strip()


def _wrap(words: list[CaptionWord], words_per_line: int, max_lines: int) -> list[list[str]]:
    lines: list[list[str]] = []
    current: list[str] = []
    for word in words:
        current.append(word.text)
        if len(current) >= words_per_line:
            lines.append(current)
            current = []
    if current:
        lines.append(current)
    if len(lines) > max_lines:
        merged = [token for line in lines for token in line]
        lines = []
        per_line = max(1, len(merged) // max_lines + 1)
        for index in range(0, len(merged), per_line):
            lines.append(merged[index : index + per_line])
        lines = lines[:max_lines]
    return lines


def _chunk(words: list[CaptionWord], settings: CaptionSettings) -> list[list[CaptionWord]]:
    capacity = max(1, settings.max_words_per_line * settings.max_lines)
    chunks: list[list[CaptionWord]] = []
    current: list[CaptionWord] = []
    for word in words:
        if current:
            gap = word.start_ms - current[-1].end_ms
            ends_sentence = current[-1].text.rstrip().endswith((".", "!", "?", "…", ","))
            if gap >= CHUNK_GAP_MS or len(current) >= capacity or (ends_sentence and len(current) >= settings.max_words_per_line):
                chunks.append(current)
                current = []
        current.append(word)
    if current:
        chunks.append(current)
    return chunks


def _render_event(chunk: list[CaptionWord], active_index: int, settings: CaptionSettings,
                  start_ms: int, end_ms: int) -> str:
    lines = _wrap(chunk, settings.max_words_per_line, settings.max_lines)
    highlight = _ass_color(settings.highlight_color)
    primary = _ass_color(settings.primary_color)
    flat_index = 0
    rendered_lines: list[str] = []
    for line in lines:
        pieces: list[str] = []
        for token in line:
            escaped = _escape(token.upper() if settings.uppercase else token)
            if flat_index == active_index:
                pieces.append(f"{{\\c{highlight}}}{escaped}{{\\c{primary}}}")
            else:
                pieces.append(escaped)
            flat_index += 1
        rendered_lines.append(" ".join(pieces))
    text = "\\N".join(rendered_lines)
    return f"Dialogue: 0,{_ass_time(start_ms)},{_ass_time(end_ms)},Caption,,0,0,0,,{text}"


def build_ass(
    spans: list[tuple[int, int]],
    words_per_span: list[list[dict]],
    spec: RenderSpec,
    width: int,
    height: int,
) -> str:
    captions = spec.captions
    scale = height / 1080 if height >= 1080 else height / 1080
    font_size = max(18, int(round(captions.font_size * scale)))
    outline = max(0.0, captions.outline_width * (height / 1080))

    border_style = 3 if captions.background else 1
    back_colour = "&H99000000" if captions.background else "&H64000000"
    outline_colour = _ass_color(captions.outline_color)

    header = [
        "[Script Info]",
        "; Generated by Clipforge",
        "ScriptType: v4.00+",
        f"PlayResX: {width}",
        f"PlayResY: {height}",
        "WrapStyle: 2",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: TV.709",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, "
        "Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, "
        "Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
        "Style: Caption,{font},{size},{primary},&H00FFFFFF,{outline_col},{back},"
        "{bold},0,0,0,100,100,0,0,{border},{outline:.1f},0,{align},80,80,{margin},1".format(
            font=captions.font_family,
            size=font_size,
            primary=_ass_color(captions.primary_color),
            outline_col=outline_colour,
            back=back_colour,
            bold=-1 if captions.bold else 0,
            border=border_style,
            outline=outline,
            align=ALIGNMENT[captions.position],
            margin=captions.margin_v,
        ),
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]

    events: list[str] = []
    timeline_cursor = 0
    for (span_start, span_end), raw_words in zip(spans, words_per_span):
        span_length = max(0, span_end - span_start)
        words: list[CaptionWord] = []
        for raw in raw_words:
            begin = max(span_start, int(raw.get("start_ms", span_start)))
            finish = min(span_end, int(raw.get("end_ms", begin + 120)))
            text = str(raw.get("word", "")).strip()
            if not text or finish <= begin:
                continue
            words.append(
                CaptionWord(
                    start_ms=timeline_cursor + (begin - span_start),
                    end_ms=timeline_cursor + max(begin - span_start + 60, finish - span_start),
                    text=text,
                )
            )
        if words:
            for chunk in _chunk(words, captions):
                chunk_start = chunk[0].start_ms
                chunk_end = min(timeline_cursor + span_length, chunk[-1].end_ms + CHUNK_TAIL_MS)
                if chunk_end <= chunk_start:
                    continue
                for index, word in enumerate(chunk):
                    start = max(chunk_start, word.start_ms)
                    end = min(chunk_end, word.end_ms if word.end_ms > start else start + 120)
                    end = max(end, start + 60)
                    # Events are timed on the assembled clip's timeline, so later
                    # segments must keep their offset rather than restart at zero.
                    events.append(_render_event(chunk, index, captions, start, end))
        timeline_cursor += span_length

    return "\n".join(header + events) + "\n"
