"""Storage contract shared by the local filesystem and object storage.

Media bytes live under opaque, generated keys. The database stores the key in
``relative_path`` and a local path in ``storage_path`` that is only a cache hint:
anything that needs the bytes asks this layer to materialise them first.
"""

from __future__ import annotations

import mimetypes
import re
from pathlib import Path
from typing import Protocol

from clipforge.errors import AppError

_KEY_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/-]*$")


class StorageObjectMissing(AppError):
    """The metadata exists but the stored bytes do not."""

    status_code = 404
    code = "storage_object_missing"


class StorageUnavailable(AppError):
    """Object storage could not be reached or rejected the credentials."""

    status_code = 503
    code = "storage_unavailable"


class StorageConfigurationError(RuntimeError):
    """Raised at startup when storage settings are incomplete or contradictory."""


def validate_key(key: str) -> str:
    """Return a safe storage key, or raise ``ValueError``.

    Keys are generated by the worker (project and asset identifiers), never by
    users. Validation exists so a corrupt database row cannot turn into a
    traversal or an unexpected object path.
    """
    if not key or len(key) > 512:
        raise ValueError("Storage key is empty or too long")
    if "\\" in key or key.startswith("/") or key.endswith("/"):
        raise ValueError("Storage key must be a relative POSIX path")
    parts = key.split("/")
    if any(part in {"", ".", ".."} for part in parts):
        raise ValueError("Storage key contains an invalid segment")
    if not _KEY_PATTERN.fullmatch(key):
        raise ValueError("Storage key contains unsupported characters")
    return key


def content_type_for(key: str) -> str:
    return mimetypes.guess_type(key)[0] or "application/octet-stream"


class StorageBackend(Protocol):
    name: str

    def path_for(self, key: str) -> Path:
        """Local path used to cache this object."""
        ...

    def exists(self, key: str) -> bool: ...

    def put_bytes(self, key: str, data: bytes, *, content_type: str | None = None) -> None: ...

    def put_file(self, key: str, source: Path, *, content_type: str | None = None) -> None: ...

    def download(self, key: str, destination: Path) -> None: ...

    def delete(self, key: str) -> None: ...

    def signed_url(self, key: str, *, expires_in: int) -> str | None: ...

    def describe(self) -> dict: ...

    def close(self) -> None: ...


def ensure_local(
    storage: StorageBackend,
    key: str | None,
    *,
    legacy_path: str | None = None,
    missing_message: str,
) -> Path:
    """Return a local file for ``key``, downloading it when the cache is cold.

    ``legacy_path`` keeps rows written before storage keys were introduced
    readable. It is only a fallback when no key exists.
    """
    if not key and not legacy_path:
        raise StorageObjectMissing(missing_message)
    path = storage.path_for(key) if key else Path(legacy_path or "")
    if path.exists():
        return path
    if key and storage.exists(key):
        storage.download(key, path)
        return path
    raise StorageObjectMissing(missing_message)


def delete_keys(storage: StorageBackend, keys: list[str | None], *, ignore_missing: bool = True) -> None:
    seen: set[str] = set()
    for key in keys:
        if not key or key in seen:
            continue
        seen.add(key)
        try:
            storage.delete(key)
        except StorageObjectMissing:
            if not ignore_missing:
                raise
